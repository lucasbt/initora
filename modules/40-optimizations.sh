#!/usr/bin/env bash
# =============================================================================
# modules/40-optimizations.sh -- Kernel and journal tuning
#
# Tasks:
#   - Kernel (sysctl): swappiness, inotify limits, and network tuning.
#   - Journald disk usage limits.
#
# The udev I/O scheduler rules, fstrim timer, and boot/session service
# disables from older versions were removed: modern Fedora kernels already
# pick sensible schedulers for NVMe/SSD, fstrim.timer is enabled by default,
# and the old tweaks mostly added risk without measurable benefit.
# =============================================================================

MODULE_NAME="40-optimizations"

module_40_optimizations() {
  log_section "Module: Performance and Optimizations"

  _configure_sysctl
  _configure_journald

  log_success "Module $MODULE_NAME completed."
}

# -----------------------------------------------------------------------------
_configure_sysctl() {
  step "Configuring kernel parameters (sysctl)"

  local conf_file="/etc/sysctl.d/99-initora.conf"

  # Idempotent: always rewrite with current config values
  run_as_root tee "$conf_file" > /dev/null << SYSCTLEOF
# Generated by initora -- $(date)
# --- Memory and Swap ---
# Reduce swap usage; ZRAM compresses in RAM before hitting disk
vm.swappiness = ${VM_SWAPPINESS:-10}

# --- Network (useful for container workloads) ---
net.core.somaxconn = 4096
net.ipv4.tcp_fastopen = 3
net.ipv4.tcp_max_syn_backlog = 4096
net.core.netdev_max_backlog = 4096

# ── Inotify: essencial para IDEs monitorar projetos grandes ───────────────────
# VS Code, Zed e ferramentas de build precisam de muitos watches
fs.inotify.max_user_watches = 524288
fs.inotify.max_user_instances = 512
SYSCTLEOF

  run_as_root sysctl --system &>/dev/null || run_as_root sysctl -p "$conf_file"
  ok "sysctl configured (swappiness=${VM_SWAPPINESS:-10})"
}

# -----------------------------------------------------------------------------
_configure_journald() {
  step "Limiting journald disk usage"

  local max_size="${JOURNALD_MAX_SIZE:-1G}"
  local max_files="${JOURNALD_MAX_FILES:-10}"
  local conf_dir="/etc/systemd/journald.conf.d"
  local conf_file="${conf_dir}/99-initora.conf"

  run_as_root mkdir -p "$conf_dir"

  local desired
  desired=$(cat << JOURNALEOF
# Generated by initora
[Journal]
SystemMaxUse=${max_size}
SystemMaxFiles=${max_files}
Compress=yes
JOURNALEOF
)

  if [[ ! -f "$conf_file" ]] || ! diff <(echo "$desired") "$conf_file" &>/dev/null; then
    echo "$desired" | run_as_root tee "$conf_file" > /dev/null
    run_as_root systemctl restart systemd-journald
    ok "journald limited to $max_size, $max_files files"
  else
    skip "journald already configured"
  fi
}

# Standalone entry point
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
  source "${SCRIPT_DIR}/utils.sh"
  source "${SCRIPT_DIR}/initora-default.config"
  [[ -f "${SETUP_HOME}/.config/initora/initora.config" ]] && \
    source "${SETUP_HOME}/.config/initora/initora.config"
  module_40_optimizations
fi
