#!/usr/bin/env bash
# migrations/0003-modern-hardware-cleanup.sh
#
# Cleans up tuning that older initora versions applied for the previous
# (Haswell-era) machine and that no longer exists in the current modules:
#
#   - /etc/udev/rules.d/60-ioschedulers.conf  (forced I/O scheduler)
#   - ~/.config/containers/storage.conf       (fuse-overlayfs override)
#   - obsolete sysctl keys in /etc/sysctl.d/99-initora.conf
#
# Only files that initora itself generated are touched. User-owned files are
# left untouched.

migration_0003_modern_hardware_cleanup() {
  step "Running migration 0003 - Modern hardware cleanup..."

  # ---------------------------------------------------------------------------
  # 1. Remove the old I/O scheduler udev rule
  # ---------------------------------------------------------------------------

  local udev_rule="/etc/udev/rules.d/60-ioschedulers.conf"

  if [[ -f "$udev_rule" ]] && grep -q "Generated by initora" "$udev_rule"; then
    run_as_root rm -f "$udev_rule"
    run_as_root udevadm control --reload-rules 2>/dev/null || true
    run_as_root udevadm trigger --type=devices --action=change 2>/dev/null || true
    log_success "Removed legacy I/O scheduler rule: $udev_rule"
  else
    log_info "Legacy I/O scheduler rule not present; nothing to do."
  fi

  # ---------------------------------------------------------------------------
  # 2. Remove the old rootless Podman storage override (fuse-overlayfs)
  # ---------------------------------------------------------------------------

  local storage_conf="${SETUP_HOME}/.config/containers/storage.conf"

  if [[ -f "$storage_conf" ]] && \
     grep -q 'mount_program = "/usr/bin/fuse-overlayfs"' "$storage_conf" && \
     grep -q '^driver = "overlay"' "$storage_conf"; then
    rm -f "$storage_conf"
    log_success "Removed legacy Podman storage override: $storage_conf"
  else
    log_info "No initora-generated Podman storage override found."
  fi

  # ---------------------------------------------------------------------------
  # 3. Drop obsolete sysctl keys, keeping the rest of the file intact
  # ---------------------------------------------------------------------------

  local sysctl_conf="/etc/sysctl.d/99-initora.conf"

  if [[ -f "$sysctl_conf" ]] && grep -q "Generated by initora" "$sysctl_conf"; then
    run_as_root sed -i \
      -e '/^[[:space:]]*vm\.vfs_cache_pressure[[:space:]]*=/d' \
      -e '/^[[:space:]]*vm\.dirty_ratio[[:space:]]*=/d' \
      -e '/^[[:space:]]*vm\.dirty_background_ratio[[:space:]]*=/d' \
      -e '/^[[:space:]]*fs\.file-max[[:space:]]*=/d' \
      "$sysctl_conf"
    run_as_root sysctl --system &>/dev/null || true
    log_success "Removed obsolete sysctl keys from: $sysctl_conf"
  else
    log_info "No initora-generated sysctl file found."
  fi

  ok "'Migration 0003 - Modern hardware cleanup' finished!"
}
